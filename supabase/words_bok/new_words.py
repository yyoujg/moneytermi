def main():
    words = {k: v for k, v in categories.load_words().items() if k < 748}   # load_words는 18_words_new.sql(이 스크립트 출력)도 읽는다
    words.update(meanings.RENAMES)
    existing = set(words.values()) | {k[0] for kids in meanings.SPLITS.values() for k in kids}
    import re
    for f in HERE.glob('16_words_refine_*.sql'):
        existing |= {m.group(1).replace("''", "'") for m in re.finditer(r"^\(\d+,'((?:[^']|'')*)',", f.read_text(), re.M)}
    names = existing | {n[1] for n in NEW}
    ids = [n[0] for n in NEW]
    assert ids == list(range(748, 748 + len(NEW))), 'id는 748부터 연속'
    for n in NEW:
        assert n[1] not in existing, f'이미 있는 단어 {n[1]}'
        bad = [r for r in n[6] if r not in names]
        assert not bad, f'{n[1]} related 없음 {bad}'
        assert 1 <= n[4] <= len(categories.TOPICS) and 1 <= n[5] <= 4

    q = lambda s: "'" + s.replace("'", "''") + "'"
    arr = lambda xs: "ARRAY[" + ','.join(q(x) for x in xs) + "]::text[]"
    rows = []
    for wid, word, meaning, detail, _t, _l, related, visuals in NEW:
        v = q(json.dumps(visuals, ensure_ascii=False)) + '::jsonb' if visuals else 'NULL'
        rows.append(f"({wid},{q(word)},{q(meaning)},{q(detail)},'',{q(refine.hint_of(word))},{arr(related)},{v})")
    out = ['-- ===== 800선에 없는 로드맵 핵심어 %d개 (new_words.py 생성 - 손으로 고치지 말 것) =====' % len(NEW),
           '-- 먼저 migration_word_source.sql, migration_word_visuals.sql 적용. 코스 배정은 categories.py(17_courses)가 한다.',
           'INSERT INTO public.words (id, word, meaning, detailed_meaning, news_example, hint, related_words, visuals) VALUES',
           ',\n'.join(rows),
           'ON CONFLICT (id) DO UPDATE SET word = EXCLUDED.word, meaning = EXCLUDED.meaning, detailed_meaning = EXCLUDED.detailed_meaning,',
           '  hint = EXCLUDED.hint, related_words = EXCLUDED.related_words, visuals = EXCLUDED.visuals;',
           '', "NOTIFY pgrst, 'reload schema';", '',
           f'SELECT count(*) FROM public.words WHERE id >= 748;  -- {len(NEW)}']
    (HERE / '18_words_new.sql').write_text('\n'.join(out) + '\n')
    print(f'18_words_new.sql: {len(NEW)}개')


if __name__ == '__main__':
    main()
